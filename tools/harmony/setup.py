"""Install the pinned Linux HarmonyOS 5.0.0 build tools outside the checkout."""
import argparse
import hashlib
import json
import platform
from pathlib import Path
import shlex
import shutil
import subprocess
import tarfile
import zipfile


def sha256(path):
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(16 * 1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def download(artifact, target):
    if not target.exists() or target.stat().st_size != artifact["bytes"]:
        print("Downloading " + target.name, flush=True)
        subprocess.run(["curl", "-fSL", "--retry", "3", "--connect-timeout", "20",
                        "-C", "-", artifact["url"], "-o", str(target)], check=True)
    if target.stat().st_size != artifact["bytes"] or sha256(target) != artifact["sha256"]:
        raise ValueError("Size/SHA-256 mismatch: " + str(target))
    print("Verified " + target.name, flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True, help="User-owned tool/cache directory outside the checkout")
    parser.add_argument("--keep-archives", action="store_true", help="Retain verified downloads after installation")
    args = parser.parse_args()
    project = Path(__file__).resolve().parents[2]
    root = args.root.resolve()
    if root == project or project in root.parents:
        raise ValueError("Choose a toolchain root outside the source checkout")
    if platform.system() != "Linux" or platform.machine() not in ("x86_64", "AMD64"):
        raise ValueError("This pinned toolchain is for Linux x64; use DevEco Studio on Windows/macOS")
    manifest = json.loads(Path(__file__).with_name("toolchain.json").read_text())
    downloads, install = root / "downloads", root / "toolchain"
    downloads.mkdir(parents=True, exist_ok=True)
    install.mkdir(parents=True, exist_ok=True)
    marker = root / "installed.json"
    expected = {name: manifest[name]["sha256"] for name in ("command_line_tools", "jdk")}
    cli = install / "command-line-tools"
    if not marker.exists() or json.loads(marker.read_text()).get("sha256") != expected:
        sdk_archive = downloads / ("commandline-tools-linux-x64-" + manifest["command_line_tools"]["version"] + ".zip")
        jdk_archive = downloads / "jdk17.tar.gz"
        download(manifest["command_line_tools"], sdk_archive)
        download(manifest["jdk"], jdk_archive)
        with zipfile.ZipFile(sdk_archive) as archive:
            required = sum(item.file_size for item in archive.infolist())
            if shutil.disk_usage(root).free < required + 1024 ** 3:
                raise ValueError("Insufficient free space for SDK extraction and build outputs")
        subprocess.run(["unzip", "-q", "-o", str(sdk_archive), "-d", str(install)], check=True)
        with tarfile.open(jdk_archive) as archive:
            # Python 3.12+ rejects archive paths outside this destination.
            archive.extractall(install, filter="data")
        marker.write_text(json.dumps({"sha256": expected}, indent=2) + "\n")
        if not args.keep_archives:
            sdk_archive.unlink()
            jdk_archive.unlink()
    java = install / ("jdk-" + manifest["jdk"]["version"])
    if not (java / "bin/java").is_file():
        raise ValueError("Pinned JDK executable not found")
    sdk = json.loads((cli / "sdk/default/sdk-pkg.json").read_text())["data"]
    if sdk["version"] != "5.0.0.71" or str(sdk["apiVersion"]) != "12":
        raise ValueError("Expected HarmonyOS 5.0.0.71 / API 12")
    node = cli / "tool/node"
    if not (node / "bin/node").is_file():
        raise ValueError("Bundled Node.js not found in pinned command line tools")
    values = {
        "HARMONY_BUILD_ROOT": str(root),
        "JAVA_HOME": str(java),
        "NODE_HOME": str(node),
        "DEVECO_SDK_HOME": str(cli / "sdk"),
        "HVIGOR_USER_HOME": str(root / "state/hvigor"),
        "npm_config_cache": str(root / "state/npm-cache"),
    }
    lines = ["# Generated by tools/harmony/setup.py; source this file before building."]
    lines.extend("export " + key + "=" + shlex.quote(value) for key, value in values.items())
    lines.append("export PATH=" + shlex.quote(str(cli / "bin")) + ':"$NODE_HOME/bin:$JAVA_HOME/bin:$PATH"')
    (root / "activate.sh").write_text("\n".join(lines) + "\n")
    print("Ready: source " + str(root / "activate.sh"), flush=True)


if __name__ == "__main__":
    main()
